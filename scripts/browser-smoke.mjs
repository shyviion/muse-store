import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'

const browserPath = process.env.MUSE_BROWSER_PATH || (process.platform === 'win32' ? 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe' : '/usr/bin/chromium')
const base = process.argv[2] || process.env.MUSE_BASE_URL || 'http://127.0.0.1:5173'
const screenshots = process.argv.includes('--screenshots') || process.env.MUSE_SCREENSHOTS === '1'
const browser = await chromium.launch({ executablePath: browserPath, headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 })
const errors = []
page.on('pageerror', error => errors.push(error.stack || error.message))
page.on('console', message => { if (message.type() === 'error' && !message.location().url.startsWith('https://images.unsplash.com/')) errors.push(`${message.location().url}:${message.location().lineNumber} ${message.text()}`) })
page.on('response', response => { if (response.status() >= 400 && response.url().includes('images.unsplash.com')) errors.push(`IMAGE ${response.status()} ${response.url()}`) })

try {
  await page.goto(base, { waitUntil: 'domcontentloaded' })
  await page.locator('.hero h1').waitFor()
  assert.match(await page.locator('.hero h1').innerText(), /Vẻ đẹp/)
  if (screenshots) await page.screenshot({ path: 'qa-home.png' })
  await page.goto(`${base}/thoi-trang`, { waitUntil: 'domcontentloaded' })
  await page.locator('.product-card').first().waitFor()
  assert.equal(await page.locator('.product-card').count(), 12)
  const imageSources = await page.locator('.product-card img').evaluateAll(images => images.map(image => image.getAttribute('src')))
  assert.equal(new Set(imageSources).size, 12, 'Fashion products need distinct images')
  if (screenshots) await page.waitForTimeout(1200)
  if (screenshots) await page.screenshot({ path: 'qa-catalog.png' })
  await page.locator('.filter-radio').filter({ hasText: 'Áo nữ' }).locator('input').check({ force: true })
  assert.equal(await page.locator('.product-card').count(), 2)
  await page.goto(`${base}/my-pham`)
  await page.locator('.product-card').first().waitFor()
  assert.equal(await page.locator('.product-card').count(), 12)
  const beautySources = await page.locator('.product-card img').evaluateAll(images => images.map(image => image.getAttribute('src')))
  assert.equal(new Set(beautySources).size, 12, 'Beauty products need distinct images')
  await page.goto(`${base}/san-pham-moi`)
  await page.locator('.product-card').first().waitFor()
  assert.ok(await page.locator('.product-card').count() > 0)
  await page.goto(`${base}/khuyen-mai`)
  await page.locator('.product-card').first().waitFor()
  assert.ok(await page.locator('.product-card').count() > 0)
  await page.goto(`${base}/tim-kiem?q=MS-F001`)
  await page.locator('.product-card').first().waitFor()
  assert.equal(await page.locator('.product-card').count(), 1)
  await page.goto(`${base}/san-pham/ao-khong-tay-trang-tinh-gian`)
  await page.locator('.detail-content h1').waitFor()
  await page.locator('.size-options button').first().click()
  await page.locator('.color-options button').first().click()
  await page.locator('.add-cart-button').click()
  await page.locator('.detail-heart').click()
  await page.goto(`${base}/yeu-thich`)
  assert.equal(await page.locator('.product-card').count(), 1)
  await page.reload()
  assert.equal(await page.locator('.product-card').count(), 1, 'Favorites must persist after reload')
  await page.goto(`${base}/gio-hang`)
  assert.equal(await page.locator('.cart-item').count(), 1)
  await page.reload()
  assert.equal(await page.locator('.cart-item').count(), 1, 'Cart must persist after reload')
  await page.goto(`${base}/thanh-toan`)
  assert.equal(await page.locator('.checkout-submit').isDisabled(), true, 'Checkout preview must require Supabase')
  await page.goto(`${base}/gioi-thieu`)
  assert.match(await page.locator('h1').first().innerText(), /muse/i)
  await page.goto(`${base}/duong-dan-khong-ton-tai`)
  assert.match(await page.locator('h1').first().innerText(), /đi lạc/i)
  await page.goto(`${base}/admin/login`)
  assert.match(await page.locator('h1').first().innerText(), /Chào mừng|ADMIN LOGIN|quản trị|Đăng nhập/i)
  if (screenshots) await page.screenshot({ path: 'qa-admin.png' })
  await page.goto(`${base}/admin`)
  await page.waitForURL(/\/admin\/login/, { timeout: 10000 })
  assert.match(page.url(), /\/admin\/login/, 'Admin route must be protected')
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
  await mobile.goto(base)
  await mobile.locator('.hero h1').waitFor()
  if (screenshots) await mobile.waitForTimeout(1700)
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth), 0, 'Mobile must not overflow horizontally')
  if (screenshots) await mobile.screenshot({ path: 'qa-mobile.png' })
  await mobile.locator('.mobile-menu-button').click()
  assert.equal(await mobile.locator('.mobile-drawer').isVisible(), true)
  await mobile.locator('.mobile-drawer-head button').click()
  await mobile.goto(`${base}/thoi-trang`)
  await mobile.locator('.product-card').first().waitFor()
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth), 0, 'Mobile catalog must not overflow')
  await mobile.close()
  assert.deepEqual(errors, [], 'Browser console errors')
  console.log('Smoke checks passed: routes, 24 unique catalog images, filters, search, detail, cart and wishlist persistence, checkout gate, admin gate, mobile menu and layout.')
} finally {
  if (errors.length) console.error('Browser errors:', errors)
  await browser.close()
}
